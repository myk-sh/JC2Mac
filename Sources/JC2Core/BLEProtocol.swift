    /// CoreBluetooth includes the two-byte company ID in manufacturer data.
    public static func side(manufacturerData: Data) -> JoyConSide? {
        let b = Array(manufacturerData)
        guard b.count >= 9, b[0] == 0x53, b[1] == 0x05,
              Array(b[2...6]) == [0x01, 0x00, 0x03, 0x7e, 0x05] else { return nil }
        switch UInt16(b[7]) | UInt16(b[8]) << 8 {
        case 0x2067: return .left
        case 0x2066: return .right
        default: return nil
        }
    }

